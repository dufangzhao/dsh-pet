import { createFixture, verifyFixture } from './application-extension-fixture.js';
import assert from 'node:assert/strict';
import path from 'node:path';
import { DesktopHost } from '../../apps/desktop/src/main/desktop-host.js';
import { DemoController } from '../../apps/desktop/src/main/demo-controller.js';
import { ApplicationController } from '../../apps/desktop/src/main/application-controller.js';
import { demoReadiness } from '../../apps/desktop/src/main/demo-readiness.js';
const root = path.resolve(__dirname, '../..');
void (async () => {
  let host: DesktopHost | undefined;
  let demo: DemoController | undefined;
  let application: ApplicationController | undefined;
  const report: Record<string, unknown> = { status: 'failed', checks: [] };
  const checks = report['checks'] as string[];
  try {
    const profile = path.join(__dirname, 'profile');
    await createFixture(path.join(profile, 'plugins'), root);
    host = await DesktopHost.create({ executable: process.execPath, workerEntry: path.join(root, 'apps/desktop/dist/runtime/worker.cjs'), builtinDirectory: path.join(root, 'plugins'), userDirectory: path.join(profile, 'plugins'), adapters: demoReadiness(path.join(root, '.cache/asr-models')), media: { input: (ref, writer) => demo ? demo.input(ref, writer) : writer.cancel(), output: (ref, reader) => demo ? demo.output(ref, reader) : reader.cancel(), capabilityTask: (parent, child, capability, method) => demo?.capabilityTask(parent, child, capability, method) } });
    let appliedName = '';
    demo = await DemoController.create(host, path.join(root, '.cache/asr-models'), () => {});
    application = await ApplicationController.create(host, demo, profile, () => {}, data => { appliedName = data.petName; });
    let state = await application.snapshot();
    assert.equal(state.pages.length, 5);
    assert.equal(state.agent.state, 'ready');
    assert.equal(state.prompt.appliedRevision, 1);
    checks.push('pinned-ordinary-pages-profile-and-Core-start-without-a-Key');
    const initial = state.dialog!;
    const name = await application.answer(initial.id, initial.step, 'next');
    assert.ok(name.ok); assert.equal(name.value.dialog?.step, 'name');
    const replay = await application.answer(initial.id, initial.step, 'next');
    assert.equal(replay.ok, false);
    const named = await application.answer(name.value.dialog!.id, 'name', 'save', '小星');
    assert.ok(named.ok); assert.equal(named.value.profile?.data.petName, '小星'); assert.equal(appliedName, '小星');
    const colored = await application.answer(named.value.dialog!.id, 'appearance', 'pine');
    assert.ok(colored.ok); assert.equal(colored.value.profile?.data.palette, 'pine');
    const voice = await application.answer(colored.value.dialog!.id, 'voice', 'enable');
    assert.ok(voice.ok);
    const provider = await application.answer(voice.value.dialog!.id, 'provider', 'demo');
    assert.ok(provider.ok);
    const done = await application.answer(provider.value.dialog!.id, 'done', 'done');
    assert.ok(done.ok); assert.equal(done.value.dialog, null);
    checks.push('pet-only-guide-directly-saves-name-appearance-and-mode-and-rejects-replay');
    const sent = await demo.sendText('你好');
    assert.ok(sent.ok, JSON.stringify(sent));
    const deadline = Date.now() + 10000;
    while (Date.now() < deadline) { const view = await demo.snapshot(); if (view.phase === 'error') throw new Error(JSON.stringify(view.error)); if (view.phase === 'idle' && view.messages.length === 2) break; await new Promise(resolve => setTimeout(resolve, 20)); }
    const view = await demo.snapshot(); assert.equal(view.messages.length, 2); assert.equal(view.phase, 'idle');
    state = await application.snapshot();
    assert.deepEqual(state.history.filter(i => i.kind === 'user' || i.kind === 'pet').map(i => i.text), view.messages.map(i => i.text));
    checks.push('native-input-adapter-and-settings-project-the-same-Core-messages');
    assert.equal((await demo.snapshot()).canRecord, true);
    const beforeVoice = (await application.snapshot()).profile!;
    const voiceDisabled = await application.saveProfile(beforeVoice.revision, { ...beforeVoice.data, voiceEnabled: false });
    assert.ok(voiceDisabled.ok);
    assert.equal((await demo.snapshot()).canRecord, false);
    assert.equal((await demo.beginRecording(42)).ok, false);
    checks.push('canonical-voice-disabled-prevents-recording-with-ready-ASR');

    const persona = (await application.snapshot()).profile!;
    const saved = await application.saveProfile(persona.revision, { ...persona.data, personaPrompt: 'Complete prompt: ' + 'x'.repeat(5000) });
    assert.ok(saved.ok, JSON.stringify(saved));
    assert.equal(saved.value.profile?.data.personaPrompt.length, 5017);
    const stale = await application.saveProfile(persona.revision, { ...persona.data, petName: 'Stale' });
    assert.equal(stale.ok, false);
    checks.push('full-prompt-above-old-bound-is-saved-with-CAS');
    for (let offset = 0; offset < 220; offset += 20) {
      const messages = Array.from({ length: 20 }, (_, index) => ({ id: 'history-page-fixture-' + (offset + index), role: (offset + index) % 2 ? 'assistant' : 'user', text: 'Pagination fixture ' + (offset + index), mode: 'demo', at: 1000 + offset + index }));
      assert.ok((await application.agent('importLegacy', { messages })).ok);
    }
    const latest = await application.getHistory(undefined, 200); assert.ok(latest.ok);
    assert.equal(latest.value.items.length, 200); assert.equal(latest.value.more, true);
    const older = await application.getHistory(latest.value.before!, 200); assert.ok(older.ok);
    assert.ok(older.value.items.length > 0); assert.equal(older.value.more, false);
    assert.ok(older.value.items.every(i => i.cursor < latest.value.before!));
    assert.equal(new Set([...older.value.items, ...latest.value.items].map(i => i.id)).size, older.value.items.length + latest.value.items.length);
    const delta = await application.agent('history', { after: 0, limit: 50 }); assert.ok(delta.ok);
    assert.equal((delta.value as Record<string, unknown>)['cursor'], 50);
    checks.push('bounded-history-pages-cover-earlier-records-and-delta-cursor-without-gaps');
    await demo.clearHistory();
    const empty = await application.snapshot(); assert.equal(empty.history.length, 0);
    checks.push('clear-removes-the-one-canonical-conversation');
    const stopped = await host.manager.disable({ pluginId: 'pet.agent-cortico', instanceId: 'default' });
    assert.ok(stopped.ok);
    await application.recordPluginStates();
    application.close();
    application = await ApplicationController.create(host, demo, profile, () => {}, () => {});
    const recoverable = await application.snapshot();
    assert.equal(recoverable.agent.state, 'stopped');
    assert.equal(recoverable.pages.length, 5);
    const cfg = await host.configs.get({ pluginId: 'pet.agent-cortico', instanceId: 'default' });
    assert.ok(cfg.ok);
    assert.ok((await host.manager.enable({ pluginId: 'pet.agent-cortico', instanceId: 'default' }, cfg.value.data)).ok);
    await application.recordPluginStates();
    assert.equal((await application.snapshot()).agent.state, 'ready');
    checks.push('stopped-agent-does-not-prevent-application-recovery-and-reattaches-on-enable');
    await verifyFixture(host, application);
    checks.push('external-owned-page-config-action-disable-fault-and-generation-recovery');
    report['status'] = 'passed';
  } catch (error) { report['failure'] = error instanceof Error ? error.stack : String(error); process.exitCode = 1; }
  finally { application?.close(); demo?.close(); if (host) report['shutdown'] = await host.shutdown(); process.send?.(report); }
})();
