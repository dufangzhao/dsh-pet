import { fork } from 'node:child_process';
import { createRequire } from 'node:module';
import { build } from 'esbuild';
import { openSync, closeSync } from 'node:fs';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const require = createRequire(import.meta.url);
const executable = path.join(path.dirname(require.resolve('electron/package.json')), 'dist/electron.exe');
const entry = path.join(root, '.cache/application-backend-' + Date.now(), 'main.cjs');
await build({ entryPoints: [path.join(root, 'qa/probes/application-backend-host.ts')], outfile: entry, bundle: true, platform: 'node', format: 'cjs', target: 'node24', external: ['electron','esbuild'] });
const stderrPath = path.join(path.dirname(entry), 'stderr.log');
const env = { ELECTRON_RUN_AS_NODE: '1' };
for (const key of ['SystemRoot','WINDIR','TEMP','TMP','PATH','USERPROFILE','APPDATA','LOCALAPPDATA']) if (process.env[key]) env[key] = process.env[key];
const result = await new Promise((resolve, reject) => {
  const fd = openSync(stderrPath, 'w');
  const child = fork(entry, [], { execPath: executable, env, windowsHide: true, serialization: 'json', stdio: ['ignore','ignore',fd,'ipc'] });
  closeSync(fd);
  let report;
  let forced = false;
  const timer = setTimeout(() => { forced = true; child.kill(); }, 60000);
  child.on('message', data => { report = data; });
  child.once('error', error => { clearTimeout(timer); reject(error); });
  child.once('exit', code => { clearTimeout(timer); resolve({ status: 'failed', ...report, exitCode: code, shutdown: { exitConfirmed: true, forced } }); });
});
result.stderr = (await fs.readFile(stderrPath, 'utf8')).slice(-6000);
await fs.writeFile(path.join(root, 'qa/application-backend-results.json'), JSON.stringify(result, null, 2) + String.fromCharCode(10));
console.log(JSON.stringify(result));
if (result.status !== 'passed' || result.exitCode !== 0) process.exitCode = 1;
