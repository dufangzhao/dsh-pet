import {build} from 'esbuild';
import {spawn} from 'node:child_process';
import {createRequire} from 'node:module';
import * as fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');const out=path.join(root,'.cache/m1-host-bridge');await fs.mkdir(out,{recursive:true});
await build({entryPoints:[path.join(root,'qa/probes/host-bridge-smoke.ts')],outfile:path.join(out,'main.cjs'),bundle:true,platform:'node',format:'cjs',target:'node24',external:['electron']});
const require=createRequire(import.meta.url);const pkg=require.resolve('electron/package.json');const env={};
for(const key of ['SystemRoot','WINDIR','TEMP','TMP','PATH','USERPROFILE','APPDATA','LOCALAPPDATA'])if(process.env[key])env[key]=process.env[key];
const child=spawn(path.join(path.dirname(pkg),'dist/electron.exe'),[path.join(out,'main.cjs'),'--m1-host-smoke'],{cwd:root,env,stdio:'inherit',windowsHide:true});
const timer=setTimeout(()=>child.kill(),30000);child.once('error',()=>{clearTimeout(timer);process.exitCode=1;});
child.once('exit',async code=>{clearTimeout(timer);let passed=false;try{passed=JSON.parse(await fs.readFile(path.join(out,'report.json'),'utf8')).status==='passed';}catch{}process.exitCode=code===0&&passed?0:1;});
